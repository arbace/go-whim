package gen

import (
	"fmt"
	"github.com/arbace/go-whim/internal/cc"
	"go/format"
	"os"
	"strings"
)

// gaGrowInner is ga_grow_inner(): the one function whose body is a rule of the
// runtime's rather than a translation (internal/gen/CONVENTIONS.md, Growarrays).  C
// allocates, copies and clears new_len bytes; GaGrowTo does it in elements of
// the storage's type.
const gaGrowInner = `func ga_grow_inner(gap *S_growarray, n int32) int32 {
	if n < gap.ga_growsize {
		n = gap.ga_growsize
	}

	if n < gap.ga_len/2 {
		n = gap.ga_len / 2
	}

	if n > 0 && usize(gap.ga_len+n) > SIZE_MAX/usize(gap.ga_itemsize) {
		return FAIL
	}
	// C allocates, copies and clears new_len bytes here; GaGrowTo does it
	// in elements of the storage's type.
	gap.ga_maxlen = gap.ga_len + n
	GaGrowTo(gap, int(gap.ga_maxlen))
	return OK
}
`

const editorHeader = `// Code generated by go tool whim gen from editor.c; DO NOT EDIT.
//
// editor.go is editor.c -- the core of whim-vim.c, everything above its first
// #include -- in Go, written by a program: internal/gen reads editor.c with
// modernc.org/cc/v4, decides for every C pointer whether it is a plain *T or
// a Ptr[T] that walks, and writes the types, the globals, their initial
// values and every function's body to internal/gen/CONVENTIONS.md.  crt.go is the C
// runtime it is written against; host.go is the host the core calls.
//
// Regenerate with make editor/editor.go (go tool whim gen).

package main

`

// writeEditor writes editor.go whole, and refuses if any function or initial
// value has no rule.
func (g *gen) writeEditor(path string, skip map[string]bool) error {
	body, report := g.bodies(skip)
	if report != "" {
		return fmt.Errorf("functions the emitter cannot write:\n%s", report)
	}
	inits, failed := g.initializers()
	if len(failed) > 0 {
		return fmt.Errorf("initial values the emitter cannot write:\n%s", strings.Join(failed, "\n"))
	}
	var b strings.Builder
	b.WriteString(editorHeader)
	b.WriteString(strings.TrimPrefix(g.typesText(), "package main\n\n"))
	b.WriteString("\n")
	b.WriteString(strings.TrimPrefix(g.globalsText(), "package main\n\n"))
	b.WriteString("\n// The initial values of the file-scope objects and the hoisted statics whose\n// C initializer is not all zeros.\nfunc init() {\n")
	b.WriteString(inits)
	b.WriteString("}\n\n")
	b.WriteString(g.gaGrowInnerText() + "\n")
	b.WriteString(body)
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("the generated file is not Go: %v", err)
	}
	return os.WriteFile(path, src, 0o644)
}

// gaGrowInnerText is gaGrowInner with the result type the C gives it: `int`,
// OK and FAIL, until phase 166 made a success bool, and then `bool`, true and
// false.  The rule is the runtime's; the signature is the C's.
func (g *gen) gaGrowInnerText() string {
	for _, n := range g.ast.Scope.Nodes["ga_grow_inner"] {
		d, ok := n.(*cc.Declarator)
		if !ok {
			continue
		}
		ft, ok := d.Type().(*cc.FunctionType)
		if !ok {
			continue
		}
		if g.goType(ft.Result(), "ret:ga_grow_inner") == "bool" {
			s := strings.Replace(gaGrowInner, "n int32) int32 {", "n int32) bool {", 1)
			s = strings.ReplaceAll(s, "return FAIL", "return false")
			return strings.ReplaceAll(s, "return OK", "return true")
		}
		break
	}
	return gaGrowInner
}
